masuk as (
  insert into public.sales (store_id, pc_id, tanggal, product_id, tipe, nama_produk, harga, qty, metode, cara_bayar, kategori_user)
  select c.store_id, c.pc_id, c.tanggal, c.product_id, 'HP', c.produk, 0, c.qty, 'Cash', 'Tunai', 'Walk-in'
    from cocok c
   where c.pc_id is not null and c.product_id is not null
     and not exists (select 1 from public.sales s where s.pc_id = c.pc_id and s.tanggal = c.tanggal and s.product_id = c.product_id)
  returning qty
)
select 'Penjualan masuk' as status,
       (select count(*) from masuk) as baris, (select coalesce(sum(qty), 0) from masuk) as unit,
       (select string_agg(distinct pc, ', ') from cocok where pc_id is null) as bukan_pc_dilewati,
       (select string_agg(distinct pc || ': ' || produk, '; ') from cocok where pc_id is not null and product_id is null) as produk_tidak_ada_di_area;
